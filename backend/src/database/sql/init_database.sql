CREATE OR ALTER PROCEDURE SP_DASHBOARD_GET_STATS
    @MAKHOA NCHAR(10) = NULL,
    @NIENKHOA NCHAR(9) = NULL,
    @HOCKY INT = NULL
AS
BEGIN
    -- Recordset 0: Thống kê tổng quan
    DECLARE @TotalStudents INT;
    DECLARE @OpenClasses INT;
    DECLARE @TotalClasses INT;
    DECLARE @TotalRegistrations INT;

    SELECT @TotalStudents = COUNT(sv.MASV)
    FROM SINHVIEN sv
    INNER JOIN LOP l ON sv.MALOP = l.MALOP
    WHERE (@MAKHOA IS NULL OR l.MAKHOA = @MAKHOA);

    SELECT @OpenClasses = COUNT(MALTC)
    FROM LOPTINCHI
    WHERE HUYLOP = 0
      AND (@MAKHOA IS NULL OR MAKHOA = @MAKHOA)
      AND (@NIENKHOA IS NULL OR NIENKHOA = @NIENKHOA)
      AND (@HOCKY IS NULL OR HOCKY = @HOCKY);

    SELECT @TotalClasses = COUNT(MALTC)
    FROM LOPTINCHI
    WHERE (@MAKHOA IS NULL OR MAKHOA = @MAKHOA)
      AND (@NIENKHOA IS NULL OR NIENKHOA = @NIENKHOA)
      AND (@HOCKY IS NULL OR HOCKY = @HOCKY);

    SELECT @TotalRegistrations = COUNT(dk.MASV)
    FROM DANGKY dk
    INNER JOIN LOPTINCHI ltc ON dk.MALTC = ltc.MALTC
    WHERE (dk.HUYDANGKY = 0 OR dk.HUYDANGKY IS NULL)
      AND (@MAKHOA IS NULL OR ltc.MAKHOA = @MAKHOA)
      AND (@NIENKHOA IS NULL OR ltc.NIENKHOA = @NIENKHOA)
      AND (@HOCKY IS NULL OR ltc.HOCKY = @HOCKY);

    SELECT @TotalStudents AS TotalStudents,
           @OpenClasses AS OpenClasses,
           @TotalClasses AS TotalClasses,
           @TotalRegistrations AS TotalRegistrations;

    -- Recordset 1: Chi tiết các lớp tín chỉ
    SELECT 
        ltc.MALTC,
        mh.TENMH,
        ltc.NHOM,
        gv.HO + ' ' + gv.TEN AS TEN_GV,
        ltc.SOSVTOITHIEU,
        (SELECT COUNT(*) FROM DANGKY dk WHERE dk.MALTC = ltc.MALTC AND (dk.HUYDANGKY = 0 OR dk.HUYDANGKY IS NULL)) AS SOSVDANGKY
    FROM LOPTINCHI ltc
    INNER JOIN MONHOC mh ON ltc.MAMH = mh.MAMH
    INNER JOIN GIANGVIEN gv ON ltc.MAGV = gv.MAGV
    WHERE (@MAKHOA IS NULL OR ltc.MAKHOA = @MAKHOA)
      AND (@NIENKHOA IS NULL OR ltc.NIENKHOA = @NIENKHOA)
      AND (@HOCKY IS NULL OR ltc.HOCKY = @HOCKY)
    ORDER BY ltc.MALTC;
END;
GO

