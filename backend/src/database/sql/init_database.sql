-- Cập nhật điểm hàng loạt cho lớp tín chỉ bằng cách truyền chuỗi JSON
CREATE OR ALTER PROCEDURE SP_UPDATE_DIEM_BATCH
    @MALTC INT,
    @JSON_DATA NVARCHAR(MAX)
AS
BEGIN
    UPDATE dk
    SET dk.DIEM_CC = jd.DIEM_CC,
        dk.DIEM_GK = jd.DIEM_GK,
        dk.DIEM_CK = jd.DIEM_CK
    FROM DANGKY dk
    INNER JOIN OPENJSON(@JSON_DATA)
    WITH (
        MASV NCHAR(10) '$.MASV',
        DIEM_CC INT '$.DIEM_CC',
        DIEM_GK FLOAT '$.DIEM_GK',
        DIEM_CK FLOAT '$.DIEM_CK'
    ) jd ON dk.MASV = jd.MASV
    WHERE dk.MALTC = @MALTC AND (dk.HUYDANGKY = 0 OR dk.HUYDANGKY IS NULL);
END;
GO

-- BÁO CÁO: Bảng điểm môn học theo lớp tín chỉ
CREATE OR ALTER PROCEDURE SP_REPORT_BANGDIEM_MONHOC
    @MALTC INT
AS
BEGIN
    SELECT 
        dk.MASV,
        sv.HO,
        sv.TEN,
        dk.DIEM_CC,
        dk.DIEM_GK,
        dk.DIEM_CK,
        (ISNULL(dk.DIEM_CC, 0) * 0.1 + ISNULL(dk.DIEM_GK, 0) * 0.3 + ISNULL(dk.DIEM_CK, 0) * 0.6) AS DIEM_KTHP
    FROM DANGKY dk
    INNER JOIN SINHVIEN sv ON dk.MASV = sv.MASV
    WHERE dk.MALTC = @MALTC AND (dk.HUYDANGKY = 0 OR dk.HUYDANGKY IS NULL)
    ORDER BY sv.TEN, sv.HO;
END;
GO

-- BÁO CÁO: Phiếu điểm cá nhân sinh viên
CREATE OR ALTER PROCEDURE SP_REPORT_PHIEUDIEM
    @MASV NCHAR(10)
AS
BEGIN
    SELECT 
        mh.TENMH,
        dk.DIEM_CC,
        dk.DIEM_GK,
        dk.DIEM_CK,
        (ISNULL(dk.DIEM_CC, 0) * 0.1 + ISNULL(dk.DIEM_GK, 0) * 0.3 + ISNULL(dk.DIEM_CK, 0) * 0.6) AS DIEM_KTHP
    FROM DANGKY dk
    INNER JOIN LOPTINCHI ltc ON dk.MALTC = ltc.MALTC
    INNER JOIN MONHOC mh ON ltc.MAMH = mh.MAMH
    WHERE dk.MASV = @MASV AND (dk.HUYDANGKY = 0 OR dk.HUYDANGKY IS NULL)
    ORDER BY mh.TENMH;
END;
GO

-- BÁO CÁO: Bảng điểm tổng kết theo lớp (Dynamic Pivot)
CREATE OR ALTER PROCEDURE SP_REPORT_BANGDIEM_TONGKET
    @MALOP NCHAR(10)
AS
BEGIN
    DECLARE @cols AS NVARCHAR(MAX),
            @query AS NVARCHAR(MAX);

    -- Lấy danh sách tên tất cả môn học mà sinh viên lớp này đã học/đăng ký
    SELECT @cols = COALESCE(@cols + ', ', '') + QUOTENAME(TENMH)
    FROM (
        SELECT DISTINCT mh.TENMH
        FROM DANGKY dk
        INNER JOIN SINHVIEN sv ON dk.MASV = sv.MASV
        INNER JOIN LOPTINCHI ltc ON dk.MALTC = ltc.MALTC
        INNER JOIN MONHOC mh ON ltc.MAMH = mh.MAMH
        WHERE sv.MALOP = @MALOP AND (dk.HUYDANGKY = 0 OR dk.HUYDANGKY IS NULL)
    ) AS Subjects;

    IF @cols IS NULL OR @cols = ''
    BEGIN
        -- Trả về danh sách sinh viên cơ bản nếu chưa có đăng ký môn nào
        SELECT MASV, HO, TEN 
        FROM SINHVIEN 
        WHERE MALOP = @MALOP;
        RETURN;
    END

    -- Sử dụng Dynamic SQL để pivot kết quả điểm tổng kết
    SET @query = '
    SELECT MASV, HO, TEN, ' + @cols + '
    FROM (
        SELECT 
            sv.MASV,
            sv.HO,
            sv.TEN,
            mh.TENMH,
            (ISNULL(dk.DIEM_CC, 0) * 0.1 + ISNULL(dk.DIEM_GK, 0) * 0.3 + ISNULL(dk.DIEM_CK, 0) * 0.6) AS DIEM_KTHP
        FROM SINHVIEN sv
        LEFT JOIN DANGKY dk ON sv.MASV = dk.MASV AND (dk.HUYDANGKY = 0 OR dk.HUYDANGKY IS NULL)
        LEFT JOIN LOPTINCHI ltc ON dk.MALTC = ltc.MALTC
        LEFT JOIN MONHOC mh ON ltc.MAMH = mh.MAMH
        WHERE sv.MALOP = ''' + @MALOP + '''
    ) src
    PIVOT (
        MAX(DIEM_KTHP)
        FOR TENMH IN (' + @cols + ')
    ) piv;';

    EXEC sp_executesql @query;
END;
GO

